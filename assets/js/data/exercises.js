/**
 * The exercise library.
 *
 * Every machine, cable move, free-weight lift and cardio piece the plans use,
 * plus the swaps for each. Written for a big-box gym (LA Fitness carries Life
 * Fitness, Hammer Strength, Matrix and Precor kit), so `look` describes what to
 * look for on the floor rather than a brand.
 *
 * Fields
 *   pattern   push | pull | legs | core | cardio — drives the pushed/pulled split
 *   muscles   primary sets count 1, secondary count 0.5 (fractional set counting,
 *             as used in Pelland et al. 2025's volume meta-regression)
 *   track     weight | bodyweight | time | cardio — what a logged set holds
 *   load      how logged weight turns into pounds moved: 'stack' (the pin
 *             number), 'pair' (two dumbbells, logged per hand, counted twice),
 *             'single' (one dumbbell), 'plates' (plates added; sled/bar not
 *             counted), 'body' (bodyweight move, counted from Setup bodyweight)
 *   step      the usual jump in pounds when it is time to go up
 *   alts      ids of exercises that hit the same muscles the same way
 */

